import React, { useState } from 'react';
import { FileText, Download, Copy, Check, Printer } from 'lucide-react';
import { Modal } from '../common/Modal';
import { Button } from '../common/Button';

export interface ReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  reportMarkdown: string;
  networkName: string;
}

export const ReportModal: React.FC<ReportModalProps> = ({
  isOpen,
  onClose,
  reportMarkdown,
  networkName
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(reportMarkdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportMarkdown], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${networkName.toLowerCase().replace(/\s+/g, '_')}_resilience_report.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  const handlePrintPdf = () => {
    const printWindow = window.open('', '_blank');
    if (!printWindow) return;
    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
        <head>
          <title>${networkName} - Executive Resilience Report</title>
          <style>
            body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, monospace; padding: 40px; color: #1e293b; line-height: 1.6; }
            h1, h2, h3 { color: #0f172a; border-bottom: 1px solid #e2e8f0; padding-bottom: 6px; }
            pre { background: #f8fafc; padding: 16px; border-radius: 8px; border: 1px solid #cbd5e1; white-space: pre-wrap; font-size: 11px; font-family: monospace; }
            @media print { body { padding: 0; } }
          </style>
        </head>
        <body>
          <h1>Executive Resilience Audit Report — ${networkName}</h1>
          <p><em>Generated by Resilience Lab Infrastructure Intelligence Platform</em></p>
          <pre>${reportMarkdown.replace(/</g, '&lt;').replace(/>/g, '&gt;')}</pre>
          <script>window.onload = function() { window.print(); };</script>
        </body>
      </html>
    `);
    printWindow.document.close();
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={`Executive Resilience Report — ${networkName}`}
      maxWidth="xl"
    >
      <div className="space-y-4 text-xs">
        <div className="flex items-center justify-between bg-slate-50 dark:bg-slate-800/60 p-3.5 rounded-xl border border-slate-200 dark:border-slate-700">
          <div className="flex items-center gap-2 text-slate-600 dark:text-slate-300 font-mono-code">
            <FileText className="w-4 h-4 text-indigo-500" />
            <span className="font-medium">Audit Telemetry Report (.md)</span>
          </div>
          <div className="flex items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              icon={copied ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
              onClick={handleCopy}
            >
              {copied ? 'Copied' : 'Copy Text'}
            </Button>
            <Button
              variant="outline"
              size="sm"
              icon={<Printer className="w-3.5 h-3.5 text-slate-500" />}
              onClick={handlePrintPdf}
            >
              Print / Save PDF
            </Button>
            <Button
              variant="brand"
              size="sm"
              icon={<Download className="w-3.5 h-3.5" />}
              onClick={handleDownload}
            >
              Download .md
            </Button>
          </div>
        </div>

        <div className="max-h-[500px] overflow-y-auto bg-dark-canvas text-slate-200 p-5 rounded-2xl border border-slate-800 font-mono-code text-[11px] leading-relaxed whitespace-pre-wrap select-text shadow-inner">
          {reportMarkdown}
        </div>
      </div>
    </Modal>
  );
};

